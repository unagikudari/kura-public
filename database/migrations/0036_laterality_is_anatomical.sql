-- Migration 0036 — left / right が誰から見た左右かを定義する
--
-- plan kura-1.0-implementation の S-8 中の指摘、2026-07-29:
-- 「right/left はその人物にとっての位置であって、カメラに向かってどちらかを意味しない
--   ですよね」→ **そのとおりだが、どこにも定義していなかった。**
--
-- ── 実害 ──
-- 0010 / 0025 で 3 つの表に laterality を足したが、列コメントは
-- 「bilateral な region の左右 (na/left/right)」としか書いていない。**誰から見た左右かが
-- 未定義**なので、注釈者が変われば (同じ人でも日が変われば) 食い違い、
-- **データが解釈不能になる**。実際に 13 行が定義の無いまま書かれている。
--
-- ── 解剖学的左右 (その人物にとっての左右) にする ──
-- 理由は 3 つ:
--   (1) 解剖学・医学の標準がこれ。「左手」は本人の左手で、正面から見れば画面の右にある。
--   (2) **カメラに依らない**。同じ体を別角度から撮り直しても事実が変わらない。
--       画面基準にすると、体の向きが変わるだけで同じ体の同じ手の left/right が反転し、
--       **カメラの情報が解剖の列に混入する** (1 つの列に 2 つの事実 = この設計が
--       繰り返し排除してきた形)。
--   (3) **画面のどちら側かは導ける**。0032 で `body_orientation` を入れたので、
--       解剖学的左右 + 体の向き → 画面上の位置が計算できる。逆向きには戻せない
--       (画面基準からは体の向きを知らないと解剖学的左右が復元できない)。
--       **導ける方を保存しない**のは orientation を保存しなかった 0019 と同じ判断。
--
-- ── NULL と 'na' を分ける ──
-- 0010 の列コメントは「NULL / na は左右を問わない」と**両者を同じ意味にしていた**。
-- 実際は違う:
--   * NULL — **言っていない**。左右を見ていない / 判らない (非捏造の既定)
--   * 'na' — **左右の別が無い**。midline の部位、または両側に等しく当てはまる
-- 「判らない」と「左右の区別が無い」を同じ値にすると、後から
-- 「注釈者は見たのか」が判らなくなる。
--
-- ── 既存 13 行の扱い ──
-- 定義より前に書かれているので、どちらの意味で書かれたか **DB からは判らない**。
-- 消さず残し、S-12 の限界として報告する。**注釈者に確認を求める** (このコメントが
-- その記録)。append-only なので誤りなら retract.py で撤回する。
--
-- ── 運用手順 ──
--   * 単一 transaction。列コメントの更新のみ (データは触らない)。
--   * ロールバック: 不要 (コメントのみ)。

BEGIN;
SET LOCAL lock_timeout = '5s';
SET search_path = kura, public;

COMMENT ON COLUMN obs_attribute.laterality IS
  '**その人物にとっての左右** (解剖学的左右)。カメラから見た左右ではない — '
  '正面を向いた人物の left は画面では右側にある。'
  'カメラに依らないので、同じ体を別角度から撮り直しても事実が変わらない。'
  '**画面のどちら側かは body_orientation (0032) と組めば導ける** ので保存しない。'
  '値: left / right / na。**NULL は「言っていない」** (見ていない・判らない)、'
  '''na'' は**左右の別が無い** (midline の部位、または両側に等しく当てはまる)。'
  'この 2 つを混ぜると「注釈者は見たのか」が後から判らなくなる。';

COMMENT ON COLUMN obs_pose.laterality IS
  '**その人物にとっての左右** (解剖学的左右)。カメラから見た左右ではない。'
  '「左腕は上げて右腕は背中」は arm_up(left) と arms_behind_back(right) の 2 観測。'
  '**NULL は「言っていない」**、''na'' は**左右の別が無い**。';

COMMENT ON COLUMN obs_relation.subject_laterality IS
  '主体側の部位の、**その人物にとっての左右** (解剖学的左右)。カメラ基準ではない。'
  '**NULL は「言っていない」**、''na'' は**左右の別が無い**。'
  '注: 2026-07-29 の本 migration より前に書かれた行は定義が無い状態で書かれており、'
  'どちらの意味かは DB からは判らない (S-12 の限界として報告する)。';

COMMENT ON COLUMN obs_relation.object_laterality IS
  '対象側の部位の、**その人物にとっての左右** (解剖学的左右)。カメラ基準ではない。'
  '**NULL は「言っていない」**、''na'' は**左右の別が無い**。';

COMMENT ON COLUMN resolved_facet.region_laterality IS
  '主体側の部位の、**その人物にとっての左右** (解剖学的左右)。観測の laterality を'
  'そのまま運ぶ — 解決の段階で画面基準へ変換しない (カメラ情報を解剖の列に混ぜない)。';

COMMENT ON COLUMN resolved_facet.object_region_laterality IS
  '関係の対象側の部位の、**その人物にとっての左右** (解剖学的左右)。';

-- body_region.laterality は**別の概念**なので混同しないよう明記する
COMMENT ON COLUMN body_region.laterality IS
  '**その部位が対で存在するか** (none / midline / bilateral)。'
  '観測側の laterality (left/right/na = どちら側か) とは別の概念 — '
  'こちらは「左右の別がありうる部位か」、あちらは「どちら側の話か」。';

COMMIT;
