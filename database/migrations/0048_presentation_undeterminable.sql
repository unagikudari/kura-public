-- Migration 0048 — 「言っていない」「断定できない」「中性的だと判断した」を書き分ける
--
-- plan kura-1.0-implementation、2026-07-31 の user 指摘:
-- 「性別については性器の有無が見えないカットでは断定することができない。
--   これはどちらのシステムでもそう。」
--
-- ── 語はあるのに定義が無かった ──
-- `gender_presentation` の説明は英語 1 行だけで、**3 つの状態の違いがどこにも
-- 書かれていない**:
--   * NULL          — 見ていない / 言っていない
--   * `ambiguous`   — **見たが断定できない** (性器も体型も手がかりにならないカット)
--   * `androgynous` — **中性的だと積極的に判断した**
-- 定義が無いので注釈者は選び分けられず、実際「断定できない」に `androgynous` が
-- 使われた (第 2 ラウンドの 753586)。0036 で laterality の NULL と 'na' を
-- 分けたのと同じ穴 — **「判らない」と「そうである」を同じ値にすると、
-- 後から「注釈者は見たのか」が判らなくなる**。
--
-- ── これは kura1 の弱点ではない ──
-- 断定できないカットがあることは**タグ空間でも同じ** (1girl/1boy を付ける根拠が無い)。
-- user 指摘のとおり**両系に共通する制約**なので、どちらかの優劣の根拠にはならない。
-- S-12 の限界として記録する。
--
-- ── 併せて: 私 (primary-cc-2) の疑義を撤回する ──
-- S-12 第 2 ラウンドの原稿に「753586 の 2 人は androgynous なので female にすれば
-- futanari が引ける」と書いたが**的外れ**だった。断定できないカットで androgynous /
-- ambiguous を選ぶのは**非捏造として正しい**。docs 側も訂正する。
--
-- ── 運用手順 ──
--   * 単一 transaction。説明の更新のみ (データは触らない)。冪等。
--   * ロールバック: 不要 (説明のみ)。

BEGIN;
SET LOCAL lock_timeout = '5s';
SET search_path = kura, public;

UPDATE gender_presentation SET description = v.d FROM (VALUES
  ('female',
   '女性表現。**見た目の話で解剖ではない** (0037) — 体と一致しない場合がある'),
  ('male',
   '男性表現。**見た目の話で解剖ではない** — 体と一致しない場合がある'),
  ('androgynous',
   '**中性的だと積極的に判断した**。どちらとも取れる特徴が実際に描かれている場合。'
   '**「判らない」ではない** — 判らないなら ambiguous、見ていないなら NULL'),
  ('ambiguous',
   '**見たが断定できない**。性器も体型も髪型も手がかりにならないカット。'
   '**「中性的」ではない** (それは androgynous) し、**「言っていない」でもない** (それは NULL)。'
   'user 指摘 2026-07-31「性器の有無が見えないカットでは断定できない」— '
   '**これはタグ空間でも同じ制約**で、どちらかの系の弱点ではない'),
  ('other',
   '上のどれでもない。**判らないときの逃げ場にしない** — 判らないなら ambiguous')
) AS v(s,d) WHERE gender_presentation.slug = v.s;

COMMENT ON COLUMN obs_identity.presentation IS
  '見た目の性別表現。**解剖 (body_region) とは独立** — 表現と体は一致しない場合がある。'
  '**3 つの状態を書き分ける**: NULL は「見ていない / 言っていない」、'
  '``ambiguous`` は「**見たが断定できない**」、``androgynous`` は「**中性的だと判断した**」。'
  '性器が見えないカットで断定できないのは**タグ空間でも同じ**なので、'
  'そこを無理に female / male で埋めない (非捏造)。'
  '**人数はここから数える** — presentation ごとの entity 数がその scene の人数。'
  'ただし ambiguous / NULL の人物は**どの人数にも入らない**ので、'
  '人数を問う query では取りこぼしになりうる (S-12 の限界)';

COMMIT;
