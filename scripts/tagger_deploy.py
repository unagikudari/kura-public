#!/usr/bin/env python3
# Description: render, check and apply this node's tagger worker units from tagger/deploy/nodes.json (the deployment SoT)
# Kind: tool
# Effects: mutating with `apply` (writes ~/.config/systemd/user/kura-tagger@*, daemon-reload, restarts the worker only if its unit changed)
# Runs-on: every tagger node (scripts/kura_checkout_pull.sh calls `apply` on each tick)
"""The tagger worker's deployment, declared once in git.

Until 2026-10-25 each node's kura-tagger@.service was a hand copy of
tagger/systemd/kura-tagger@.service (made 2026-07-20) plus hand-written drop-ins, and
nothing kept them in step: three nodes, three different files, and the knowledge of why
(nodeb's ROCm env, trainer's quotas, primary's Restart=on-failure) lived in comments on the
nodes themselves.

Now:
    tagger/deploy/nodes.json   per node: checkout, venv, models dir, profiles, env, service
                               overrides, per-profile overrides, drop-ins it replaces
    tagger/systemd/kura-tagger@.service   the template
    this script                renders them; `apply` writes this node's files

    render [--host H]   print the files H gets
    check  [--host H]   compare with what is installed here; exit 1 on drift
    apply               write this node's files, remove the drop-ins it absorbs,
                        daemon-reload, restart a running worker whose unit changed

The node is this machine's short hostname; one that is not declared is left alone.
`home` must equal $HOME, so a copy of the repo on the wrong machine cannot write
another node's paths. What a node is for (its profile) is the DB's
tagger_expected_worker; where it can read the DB, `apply` warns when they disagree.
"""
from __future__ import annotations

import argparse
import json
import os
import socket
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DECLARATION = REPO / "tagger" / "deploy" / "nodes.json"
UNIT = ".config/systemd/user/kura-tagger@.service"
#: Present from the first write until reload and restart have both succeeded. Without it
#: a failed daemon-reload or restart could never be retried: the files on disk already
#: match, so the next tick would see no drift (Codex review of 1.265.0). It lists the
#: worker units that were running when the change began: those are brought back up on a
#: retry even if the failed restart left them stopped, while a unit that was already
#: stopped on purpose (primary's full, started by its poll timer) is left alone.
PENDING = ".local/state/kura-tagger-deploy/pending"
HEADER = ("# Generated by scripts/tagger_deploy.py from tagger/deploy/nodes.json (node {node}).\n"
          "# Do not edit here: the next kura-checkout-pull tick writes it back. Edit nodes.json.\n")


def load(path: Path = DECLARATION) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def _notes(lines: list[str]) -> str:
    return "".join(f"# {line}\n" for line in lines)


def _service_block(text: str, overrides: dict[str, str], env: dict[str, str], notes: list[str]) -> str:
    """Apply overrides to the template's [Service] section, add env and notes."""
    out, section = [], None
    keys = dict(overrides)
    for line in text.splitlines(keepends=True):
        stripped = line.strip()
        if stripped.startswith("[") and stripped.endswith("]"):
            if section == "[Service]":
                out.extend(f"{k}={v}\n" for k, v in keys.items())
                keys = {}
            section = stripped
            out.append(line)
            if section == "[Service]" and notes:
                out.append(_notes(notes))
            continue
        if section == "[Service]" and "=" in stripped and not stripped.startswith("#"):
            key = stripped.split("=", 1)[0]
            if key in keys:
                out.append(f"{key}={keys.pop(key)}\n")
                continue
            out.append(line)
            if stripped == "Environment=TAGGER_PROFILE=%i":
                out.extend(f"Environment={k}={v}\n" for k, v in env.items())
            continue
        out.append(line)
    if section == "[Service]":
        out.extend(f"{k}={v}\n" for k, v in keys.items())
    return "".join(out)


def _resolve(decl: dict, env: dict[str, str]) -> dict[str, str]:
    """Substitute @canonical.<key> references; an unknown reference is an error, not a literal."""
    canonical = decl.get("canonical", {})
    out = {}
    for key, value in env.items():
        if isinstance(value, str) and value.startswith("@canonical."):
            field = value[len("@canonical."):]
            if field not in canonical:
                raise ValueError(f"{key}={value}: nodes.json has no canonical.{field}")
            value = str(canonical[field])
        out[key] = value
    return out


def render(decl: dict, host: str) -> dict[str, str]:
    """{path relative to the node's home: content} for one node."""
    node = decl["nodes"][host]
    template = (REPO / decl["template"]).read_text(encoding="utf-8")
    text = (template.replace("__KURA_REPO__", node["checkout"])
            .replace("__MODELS_DIR__", node["models_dir"])
            .replace("__VENV__", node["venv"]))
    for placeholder in ("__KURA_REPO__", "__MODELS_DIR__", "__VENV__"):
        assert placeholder not in text, placeholder
    env = _resolve(decl, node.get("env", {}))
    files = {UNIT: HEADER.format(node=host) + _service_block(
        text, node.get("service", {}), env, node.get("notes", []))}
    for profile, inst in node.get("instances", {}).items():
        if profile not in node["profiles"]:
            raise ValueError(f"{host}: instance {profile!r} is not one of its profiles")
        body = HEADER.format(node=host) + _notes(inst.get("notes", [])) + "[Service]\n"
        body += "".join(f"{k}={v}\n" for k, v in inst.get("service", {}).items())
        body += "".join(f"Environment={k}={v}\n" for k, v in _resolve(decl, inst.get("env", {})).items())
        files[f".config/systemd/user/kura-tagger@{profile}.service.d/50-deploy.conf"] = body
    return files


def this_host() -> str:
    return socket.gethostname().split(".")[0]


def _drift(decl: dict, host: str, home: Path) -> tuple[dict[str, str], list[str]]:
    files = render(decl, host)
    changed = {rel: body for rel, body in files.items()
               if not (home / rel).is_file() or (home / rel).read_text(encoding="utf-8") != body}
    absorbed = [rel for rel in decl["nodes"][host].get("absorbs", []) if (home / rel).exists()]
    return changed, absorbed


def _systemctl(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["systemctl", "--user", *args], capture_output=True, text=True)


def _check_roles(host: str, profiles: list[str]) -> None:
    """Warn when the DB's tagger_expected_worker disagrees. Silent where there is no DB."""
    env_file = REPO / "api" / "env"
    url = os.environ.get("DATABASE_URL")
    role = os.environ.get("KURA_DB_ROLE")
    if env_file.is_file():
        for line in env_file.read_text(encoding="utf-8").splitlines():
            if line.startswith("DATABASE_URL=") and not url:
                url = line.split("=", 1)[1].strip()
            if line.startswith("KURA_DB_ROLE=") and not role:
                role = line.split("=", 1)[1].strip()
    # Only the canonical node's table decides. A replica's tagger_expected_worker held 2 of
    # 5 rows on 2026-10-25, and comparing against it reported three false mismatches.
    if not url or role in ("replica", "rehearsal"):
        return
    try:
        import psycopg2
        conn = psycopg2.connect(url.replace("postgresql+asyncpg://", "postgresql://"), connect_timeout=3)
    except Exception:  # noqa: BLE001 — no DB here: nothing to compare against
        return
    try:
        cur = conn.cursor()
        cur.execute("SELECT host, profile FROM tagger_expected_worker")
        expected = dict(cur.fetchall())
    except Exception:  # noqa: BLE001
        return
    finally:
        conn.close()
    declared = {h: n["profiles"] for h, n in load()["nodes"].items()}
    for h in sorted(set(expected) | set(declared)):
        if [expected.get(h)] != declared.get(h, [None]):
            print(f"tagger-deploy: role mismatch for {h}: tagger_expected_worker={expected.get(h)!r} "
                  f"nodes.json={declared.get(h)!r} — the DB decides the role; fix nodes.json or the DB",
                  file=sys.stderr)


def apply(decl: dict, host: str, home: Path, *, dry_run: bool = False,
          restarted_file: Path | None = None) -> int:
    """Converge this node. Returns non-zero when anything failed; the next run retries.

    `restarted_file` (set by kura_checkout_pull.sh): the units restarted here are appended
    to it, so the pull tick does not restart them a second time for the same code.
    """
    node = decl["nodes"][host]
    if Path(node["home"]) != home:
        print(f"tagger-deploy: refusing: nodes.json says {host}'s home is {node['home']}, "
              f"this is {home}", file=sys.stderr)
        return 2
    changed, absorbed = _drift(decl, host, home)
    pending = home / PENDING
    if not changed and not absorbed and not pending.exists():
        _check_roles(host, node["profiles"])
        return 0
    if pending.exists():
        print("tagger-deploy: a previous run did not finish reload/restart — retrying")
        running = [u for u in pending.read_text(encoding="utf-8").split() if u.endswith(".service")]
    else:
        running = [f"kura-tagger@{p}.service" for p in node["profiles"]
                   if _systemctl("is-active", "--quiet", f"kura-tagger@{p}.service").returncode == 0]
    for rel in changed:
        print(f"tagger-deploy: {'would write' if dry_run else 'write'} {rel}")
    for rel in absorbed:
        print(f"tagger-deploy: {'would remove' if dry_run else 'remove'} {rel} (absorbed into nodes.json)")
    if dry_run:
        return 0
    pending.parent.mkdir(parents=True, exist_ok=True)
    pending.write_text("".join(f"{u}\n" for u in running))   # empty: nothing was running
    for rel, body in changed.items():
        path = home / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_name(path.name + ".tmp")
        tmp.write_text(body, encoding="utf-8")
        os.replace(tmp, path)
    for rel in absorbed:
        (home / rel).unlink()
        try:
            (home / rel).parent.rmdir()   # only if now empty
        except OSError:
            pass
    reload = _systemctl("daemon-reload")
    if reload.returncode != 0:
        print(f"tagger-deploy: daemon-reload failed ({(reload.stderr or '').strip()}) — "
              "will retry on the next run", file=sys.stderr)
        return 1
    failed = False
    # Units that were not running when the change began are left stopped: the new unit
    # applies when they next start. Those that were running are restarted (restart, not
    # try-restart: a retry must also bring back one a failed restart left stopped).
    for unit in running:
        result = _systemctl("restart", unit)
        if result.returncode != 0:
            print(f"tagger-deploy: restart of {unit} failed ({(result.stderr or '').strip()})",
                  file=sys.stderr)
            failed = True
            continue
        print(f"tagger-deploy: restarted {unit}")
        if restarted_file is not None:
            with restarted_file.open("a", encoding="utf-8") as f:
                f.write(unit + "\n")
    if failed:
        return 1
    pending.unlink(missing_ok=True)
    _check_roles(host, node["profiles"])
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", choices=("render", "check", "apply"))
    ap.add_argument("--host", default=None, help="node name (default: this machine's short hostname)")
    ap.add_argument("--dry-run", action="store_true", help="apply: say what would change, change nothing")
    ap.add_argument("--restarted-file", type=Path, default=None,
                    help="apply: append the units restarted here (kura_checkout_pull.sh skips them)")
    a = ap.parse_args(argv)
    decl = load()
    host = a.host or this_host()
    if host not in decl["nodes"]:
        if a.command == "apply":
            return 0      # not a tagger node: nothing to deploy here
        print(f"tagger-deploy: {host} is not declared in {DECLARATION.relative_to(REPO)}", file=sys.stderr)
        return 2
    if a.command == "render":
        for rel, body in render(decl, host).items():
            print(f"==> ~/{rel}\n{body}")
        return 0
    home = Path(os.environ.get("HOME", str(Path.home())))
    if a.command == "check":
        changed, absorbed = _drift(decl, host, Path(decl["nodes"][host]["home"]) if a.host else home)
        for rel in changed:
            print(f"drift: ~/{rel} differs from nodes.json")
        for rel in absorbed:
            print(f"drift: ~/{rel} still exists (absorbed into nodes.json)")
        pending = (home / PENDING).exists() and not a.host
        if pending:
            print(f"drift: ~/{PENDING} exists (a previous apply did not finish)")
        return 1 if changed or absorbed or pending else 0
    if a.host and a.host != this_host():
        print("tagger-deploy: apply only acts on this machine; drop --host", file=sys.stderr)
        return 2
    return apply(decl, host, home, dry_run=a.dry_run, restarted_file=a.restarted_file)


if __name__ == "__main__":
    sys.exit(main())
