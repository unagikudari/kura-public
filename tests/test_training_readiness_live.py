def frozen(tmp_path,monkeypatch,ids=None):
    root=tmp_path/'queues';root.mkdir()
    def put(body):
        raw=json.dumps(body,sort_keys=True).encode();sha=hashlib.sha256(raw).hexdigest()
        (root/(sha+'.json')).write_bytes(raw);return sha
    q=queue();q.pop('queue_sha256');q.update(purpose='training_support')
    if ids is not None:
        q['post_ids']=ids;q['media_sha256']={str(i):'b'*64 for i in ids}
    old={k:v for k,v in q.items() if k not in ('source_provenance','media_sha256')};old['schema']='human-review-set/1'
    oldsha=put(old)
    q['source_provenance']=dict(kind='frozen_training_support',artifact_sha256='c'*64,supersedes_queue_sha256=oldsha)
    sha=put(q)
    monkeypatch.setenv('KURA_REVIEW_QUEUE_DIR',str(root));monkeypatch.setenv('KURA_DB_ROLE','canonical')
    return service.frozen_queue(sha),oldsha


def test_actual_responses_readonly_groups_unknown_and_sync_restore(url,tmp_path,monkeypatch):
    async def go():
        engine,ss=await setup(url);q,_=frozen(tmp_path,monkeypatch)
        try:
            async with ss() as db:
                before=await snapshot(db)
                await db.execute(text("SET LOCAL statement_timeout='13s'"))
                # The separate read must not commit/rollback this caller's work.
                await db.execute(text("UPDATE post SET version=77 WHERE id=101"))
                report=await service.read(q['queue_sha256'],engine)
                assert report['counts']=={'unseen':2}
                assert (await db.execute(text('SELECT version FROM post WHERE id=101'))).scalar_one()==77
                assert (await db.execute(text('SHOW statement_timeout'))).scalar_one()=='13s'
                await db.rollback()
            await submit(ss,q,101,'uncertain');await submit(ss,q,102,'uncertain')
            async with ss() as db:assert await snapshot(db)==before
            report=await service.read(q['queue_sha256'],engine)
            assert report['counts']=={'uncertain':2} and report['excluded_from_next_training']==2
            assert report['groups'] is None and report['groups_state']=='not_measured'
            assert report['next']=='await_optional_response_changes'
            assert report['quality_granted'] is False and report['training_dispatched'] is False
            assert report['sha256']==service.digest({k:v for k,v in report.items() if k!='sha256'})
            assert report['population_sha256']==service.digest([101,102])
            await submit(ss,q,101,'present');await submit(ss,q,102,'absent')
            report=await service.read(q['queue_sha256'],engine)
            assert report['state']=='responses_bound_not_qualified'
            assert report['current_definite']=={'positive':1,'negative':1}
            await submit(ss,q,101,'absent')
            report=await service.read(q['queue_sha256'],engine)
            assert report['counts']['gt_not_synced_to_response']==1 and report['next']=='await_gt_synchronization'
            async with ss() as db:
                await db.execute(text('SELECT tagger_governed_sync_neg_gt_from_pins()'));await db.commit()
            assert (await service.read(q['queue_sha256'],engine))['current_definite']=={'positive':0,'negative':2}
        finally:await engine.dispose()
    asyncio.run(go())


def test_same_exported_snapshot_sync_async_bytes_and_membership(url,tmp_path,monkeypatch):
    async def go():
        engine,ss=await setup(url);q,_=frozen(tmp_path,monkeypatch);c=connect(url)
        try:
            await submit(ss,q,101,'uncertain');await submit(ss,q,102,'absent')
            with e.read_snapshot(c):
                snap=query(c,'SELECT pg_export_snapshot()')[0][0]
                sync=e.load(lambda sql,args:query(c,sql,args),'fixture',post_ids=[101])
                async with engine.connect() as conn:
                    conn=await conn.execution_options(isolation_level='REPEATABLE READ')
                    async with conn.begin():
                        await conn.execute(text('SET TRANSACTION READ ONLY'))
                        # Generated by our private PG; SQL SET cannot parameterize snapshot IDs.
                        import re
                        assert re.fullmatch('[0-9A-F-]+',snap)
                        await conn.execute(text("SET TRANSACTION SNAPSHOT '"+snap+"'"))
                        snapshot_id=(await conn.execute(text('SELECT txid_current_snapshot()::text'))).scalar_one()
                        asynchronous=await service.overlay(conn,'fixture',snapshot_id,[101])
                assert asynchronous==sync and len(sync['entries'])==1
                assert sync['entries'][0]['post_id']==101
        finally:c.close();await engine.dispose()
    asyncio.run(go())


def test_concurrent_commit_between_reads_cannot_mix_snapshots(url,tmp_path,monkeypatch):
    async def go():
        engine,ss=await setup(url);q,_=frozen(tmp_path,monkeypatch)
        original=service.overlay;calls=[]
        async def interleave(*args,**kw):
            result=await original(*args,**kw);calls.append(result)
            if len(calls)==1:await submit(ss,q,101,'uncertain')
            return result
        monkeypatch.setattr(service,'overlay',interleave)
        try:
            report=await service.read(q['queue_sha256'],engine)
            assert report['counts']=={'unseen':2} and report['excluded_from_next_training']==0
            assert calls[0]['transaction_snapshot']==calls[1]['transaction_snapshot']
            monkeypatch.setattr(service,'overlay',original)
            assert (await service.read(q['queue_sha256'],engine))['counts']=={'uncertain':1,'unseen':1}
        finally:await engine.dispose()
    asyncio.run(go())


@pytest.mark.parametrize('case',['replica','missing_ledger','locked_ledger','total_timeout'])
def test_unavailable_is_refusal_not_zero(url,tmp_path,monkeypatch,case):
    async def go():
        engine,ss=await setup(url);q,_=frozen(tmp_path,monkeypatch)
        try:
            async with ss() as holder:
                if case=='replica':monkeypatch.setenv('KURA_DB_ROLE','replica')
                if case=='missing_ledger':
                    await holder.execute(text('ALTER TABLE tagger_human_review_event RENAME TO fixture_missing'));await holder.commit()
                if case=='locked_ledger':await holder.execute(text('LOCK TABLE tagger_human_review_event IN ACCESS EXCLUSIVE MODE'))
                if case=='total_timeout':
                    monkeypatch.setattr(service,'TOTAL_TIMEOUT_S',.05)
                    async def slow(*a,**kw):await asyncio.sleep(1)
                    monkeypatch.setattr(service,'overlay',slow)
                import time
                started=time.monotonic()
                with pytest.raises(KuraError) as caught:await service.read(q['queue_sha256'],engine)
                if case=='locked_ledger':assert .7<time.monotonic()-started<4
                if case=='total_timeout':assert time.monotonic()-started<1
                assert caught.value.status==503
                assert 'raw' not in str(caught.value.body())
                await holder.rollback()
        finally:await engine.dispose()
    asyncio.run(go())


